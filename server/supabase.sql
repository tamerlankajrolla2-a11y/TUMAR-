-- Вставьте целиком в Supabase → SQL Editor → New query → Run

-- Заявки на банкеты и столики
create table if not exists bookings (
  id             bigint generated by default as identity primary key,
  created_at     timestamptz not null default now(),
  kind           text not null default 'banquet' check (kind in ('banquet', 'table')),
  event_date     date not null,
  event_time     text,
  guests         integer not null check (guests between 1 and 500),
  event_type     text,
  name           text not null,
  phone          text not null,
  comment        text,
  preorder       text,
  preorder_total integer,
  source         text not null default 'site',
  status         text not null default 'new' check (status in ('new', 'confirmed', 'cancelled')),
  admin_note     text,
  updated_at     timestamptz
);
create index if not exists bookings_date_idx  on bookings (event_date);
create index if not exists bookings_phone_idx on bookings (phone, created_at);

-- Даты, закрытые вручную (своё мероприятие, бронь по телефону, выходной)
create table if not exists blocked_dates (
  date       date primary key,
  reason     text,
  created_at timestamptz not null default now()
);

-- Настройки сайта из админки: меню с ценами (menu) и объявление (notice)
create table if not exists settings (
  key        text primary key,
  value      jsonb not null,
  updated_at timestamptz not null default now(),
  check (pg_column_size(value) < 600000)
);

-- Права: гости сайта только читают настройки; всё остальное — только вошедший администратор
alter table bookings      enable row level security;
alter table blocked_dates enable row level security;
alter table settings      enable row level security;

drop policy if exists "admin all" on bookings;
create policy "admin all" on bookings for all to authenticated using (true) with check (true);
drop policy if exists "admin all" on blocked_dates;
create policy "admin all" on blocked_dates for all to authenticated using (true) with check (true);
drop policy if exists "read all" on settings;
create policy "read all" on settings for select using (true);
drop policy if exists "admin write" on settings;
create policy "admin write" on settings for all to authenticated using (true) with check (true);

-- Сегодня по времени Казахстана (UTC+5)
create or replace function kz_today() returns date
language sql stable as $$ select ((now() at time zone 'UTC') + interval '5 hours')::date $$;

-- Занятые даты для календаря на сайте (видны только даты, без имён и телефонов)
create or replace function busy_dates(d_from date default null, d_to date default null)
returns setof date
language sql stable security definer set search_path = public as $$
  select d from (
    select event_date as d from bookings
      where status = 'confirmed' and kind = 'banquet'
        and event_date between coalesce(d_from, kz_today()) and coalesce(d_to, kz_today() + 400)
    union
    select date as d from blocked_dates
      where date between coalesce(d_from, kz_today()) and coalesce(d_to, kz_today() + 400)
  ) x order by d
$$;

-- Новая заявка с сайта (проверки на сервере, гости не видят чужие заявки)
create or replace function create_booking(p jsonb)
returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_kind   text := case when p->>'kind' = 'table' then 'table' else 'banquet' end;
  v_date   date;
  v_time   text := nullif(left(trim(coalesce(p->>'time', '')), 5), '');
  v_guests integer;
  v_name   text := left(trim(coalesce(p->>'name', '')), 80);
  v_digits text := regexp_replace(coalesce(p->>'phone', ''), '\D', '', 'g');
  v_phone  text;
  v_total  integer;
  v_id     bigint;
begin
  if coalesce(p->>'website', '') <> '' then return jsonb_build_object('ok', true, 'id', 0); end if;  -- ловушка для спам-ботов
  begin v_date := (p->>'date')::date; exception when others then v_date := null; end;
  if v_date is null then return jsonb_build_object('ok', false, 'error', 'Укажите дату'); end if;
  if v_date < kz_today() then return jsonb_build_object('ok', false, 'error', 'Эта дата уже прошла'); end if;
  if v_date > kz_today() + 730 then return jsonb_build_object('ok', false, 'error', 'Бронируем не дальше чем на 2 года вперёд'); end if;
  if v_time is not null and v_time !~ '^([01]\d|2[0-3]):[0-5]\d$' then return jsonb_build_object('ok', false, 'error', 'Время в формате ЧЧ:ММ'); end if;
  begin v_guests := (p->>'guests')::integer; exception when others then v_guests := null; end;
  if v_guests is null or v_guests < 1 or v_guests > 500 then return jsonb_build_object('ok', false, 'error', 'Гостей — от 1 до 500'); end if;
  if length(v_name) < 2 then return jsonb_build_object('ok', false, 'error', 'Укажите имя'); end if;
  if length(v_digits) < 10 or length(v_digits) > 15 then return jsonb_build_object('ok', false, 'error', 'Проверьте номер телефона'); end if;
  if length(v_digits) = 10 then v_digits := '7' || v_digits; end if;
  if length(v_digits) = 11 and left(v_digits, 1) = '8' then v_digits := '7' || substr(v_digits, 2); end if;
  v_phone := '+' || v_digits;
  begin v_total := (p->>'preorder_total')::integer; exception when others then v_total := null; end;
  if v_total is not null and (v_total < 0 or v_total > 100000000) then v_total := null; end if;

  if exists (select 1 from busy_dates(v_date, v_date)) then
    return jsonb_build_object('ok', false, 'busy', true, 'error', 'В этот день зал уже занят — выберите другую дату или позвоните администратору');
  end if;
  if (select count(*) from bookings where phone = v_phone and created_at > now() - interval '10 minutes') >= 3 then
    return jsonb_build_object('ok', false, 'error', 'Слишком много заявок подряд. Администратор уже получил ваши заявки.');
  end if;

  insert into bookings (kind, event_date, event_time, guests, event_type, name, phone, comment, preorder, preorder_total, source)
  values (v_kind, v_date, v_time, v_guests,
          nullif(left(trim(coalesce(p->>'type', '')), 60), ''), v_name, v_phone,
          nullif(left(trim(coalesce(p->>'comment', '')), 1000), ''),
          nullif(left(coalesce(p->>'preorder', ''), 4000), ''), v_total, 'site')
  returning id into v_id;
  return jsonb_build_object('ok', true, 'id', v_id);
end $$;

revoke all on function create_booking(jsonb) from public;
grant execute on function create_booking(jsonb) to anon, authenticated;
grant execute on function busy_dates(date, date) to anon, authenticated;
grant execute on function kz_today() to anon, authenticated;
